const assert = require('node:assert/strict');
const create = require('../web/kick-context.js');
let calls = [], name = 'kick.com/example · 480p / 30 fps';
const av = { open(...args) { calls.push({owner:this,args}); if(args[0]==='fail')throw Error('native'); return 42; } };
const context = create({webapis:{avplay:av},document:{getElementById(){return {textContent:name};}}});
const initial = context();
assert.equal(initial.title,null,'a channel label is not a broadcast title');
assert.equal(initial.live,true);
assert.equal(av.open('https://private.invalid/one?token=secret',7),42);
assert.equal(calls[0].owner,av);
assert.deepEqual(calls[0].args,['https://private.invalid/one?token=secret',7]);
assert.notEqual(context().key,initial.key);
const first = context().key;
av.open('https://private.invalid/one?token=secret');
assert.notEqual(context().key,first,'same-source reopen replaces player generation');
const stable = context().key;
assert.throws(()=>av.open('fail'),/native/);
assert.equal(context().key,stable,'failed native open preserves generation');
name='kick.com/another · 720p';
assert.equal(context().title,null);
assert.notEqual(context().key,stable);
assert.throws(()=>create({webapis:{avplay:Object.freeze({open(){}})}}));
console.log('Kick AVPlay context checks passed');

let now = 10000, requests = [], channelName = 'kick.com/example · quality', menu = false, ready = true;
function Xhr() { requests.push(this); }
Xhr.prototype.open = function (method, url) { this.method = method; this.url = url; };
Xhr.prototype.setRequestHeader = function () {};
Xhr.prototype.send = function () {};
Xhr.prototype.abort = function () { this.onabort(); };
function reply(xhr, slug, title, live = true) {
  xhr.status = 200; xhr.responseText = JSON.stringify({ slug, livestream: live ? { session_title: title, is_live: true } : null });
  xhr.onload();
}
const native = { open() { return 9; } };
const enriched = create({ webapis: { avplay: native }, XMLHttpRequest: Xhr, now: () => now,
  document: { readyState: 'complete', getElementById(id) {
    if (id === 'nowPlaying') return { textContent: channelName };
    return { classList: { contains: cls => id === 'home' ? cls === 'hidden' && !menu : cls === 'hidden' ? menu : cls === 'player-ready' && ready } };
  } } });
assert.equal(enriched().title, null);
assert.equal(requests.length, 1);
assert.equal(requests[0].url, 'https://kick.com/api/v2/channels/example');
const leaseKey = enriched().key;
reply(requests[0], 'example', 'Actual Kick broadcast');
assert.equal(enriched().title, 'Actual Kick broadcast');
assert.equal(enriched().key, leaseKey);
assert.equal(requests.length, 1, 'HA reads do not repeatedly fetch metadata');
now += 31000; enriched();
reply(requests[1], 'example', 'Edited broadcast');
assert.equal(enriched().title, 'Edited broadcast');
assert.equal(enriched().key, leaseKey, 'title updates preserve playback ownership');
ready = false;
assert.equal(enriched().title, null, 'channel/loading UI cannot relabel old buffered playback');
const beforeReady = requests.length;
enriched(); assert.equal(requests.length, beforeReady);
ready = true; now += 31000; enriched();
reply(requests.at(-1), 'example', 'Restored title');
now += 31000; enriched(); const oldRequest = requests.at(-1);
channelName = 'kick.com/another · quality';
assert.equal(enriched().title, null);
reply(oldRequest, 'example', 'Late old channel');
now += 5000; enriched();
reply(requests.at(-1), 'another', 'Other broadcast');
assert.equal(enriched().title, 'Other broadcast');
native.open('https://private.invalid/new-generation');
assert.equal(enriched().title, null, 'a native reopen clears the old generation title');
now += 5000; enriched();
reply(requests.at(-1), 'wrong-channel', 'Wrong title');
assert.equal(enriched().title, null);
now += 5000; enriched();
reply(requests.at(-1), 'another', 'Recovered title');
assert.equal(enriched().title, 'Recovered title');
now += 91000; enriched();
assert.equal(enriched().title, null, 'unrefreshed titles expire');
reply(requests.at(-1), 'another', '', false);
assert.equal(enriched().title, null, 'offline response does not invent a title');
menu = true;
assert.equal(enriched.isMenu(), true);
menu = false;
assert.equal(enriched.isMenu(), false);
assert.ok(!JSON.stringify({ title: enriched().title }).includes('private.invalid'));
console.log('Kick cached broadcast title, generation and race checks passed');
